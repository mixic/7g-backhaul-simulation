"""Run the round-3 P17 follow-up.

Examples (Linux, as root)::

    python3 -m validation.round3.run --probe
    python3 -m validation.round3.run --dry-run --only P17a
    python3 -m validation.round3.run --only P17a --runs 1
    python3 -m validation.round3.run                     # 20 runs per case

Outputs go to ``validation/round3/results``.  Interpretation belongs in
``docs/layering-real-stack-results-round3.md``.
"""

from __future__ import annotations

import argparse
import csv
import os
import platform
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

from validation.layering._io import write_observations
from validation.real_stack.shell import REPO_ROOT, CommandError, Shell
from validation.round2.net import cleanup_leftovers
from validation.round2.probe import probe

from .cases import run_case, select_cases
from .verdict import (
    NOT_RUN,
    all_verdicts,
    brier_score,
    calibration_table,
)

DEFAULT_OUTPUT = REPO_ROOT / "validation" / "round3" / "results"
PREDICTIONS_COMMIT = "285c8e9"


def environment_record(shell: Shell) -> str:
    def first_line(argv: list[str]) -> str:
        if shutil.which(argv[0]) is None:
            return "not installed"
        result = shell.run(argv, check=False)
        text = (result.stdout or result.stderr).strip().splitlines()
        return text[0] if text else "unknown"

    try:
        proc_version = Path("/proc/version").read_text(encoding="utf-8").strip()
    except OSError:
        proc_version = "unavailable"
    lines = [
        f"date_utc: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"predictions_commit: {PREDICTIONS_COMMIT}",
        "predictions_file: docs/layering-real-stack-predictions-round3.md (frozen, never edited)",
        f"python: {platform.python_version()}",
        f"kernel: {platform.release()}",
        f"proc_version: {proc_version}",
        f"wsl2: {'microsoft' in proc_version.lower()}",
        f"uid: {os.geteuid() if hasattr(os, 'geteuid') else 'windows'}",
        f"ip: {first_line(['ip', '-V'])}",
        f"tc: {first_line(['tc', '-V'])}",
        f"nft: {first_line(['nft', '--version'])}",
    ]
    return "\n".join(lines) + "\n"


def write_verdicts(path: Path, verdicts: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=("prediction", "case", "verdict", "detail"))
        writer.writeheader()
        writer.writerows(verdicts)


def write_summary(
    path: Path,
    environment: str,
    verdicts: list[dict[str, str]],
    runs: int,
    brier: float,
    scored: int,
    missing: list[str],
    unscored: list[str],
) -> None:
    lines = [
        "# Round-3 real-stack run summary (generated)",
        "",
        "Generated by `python -m validation.round3.run`; **do not edit by hand**.",
        "Interpretation belongs in `docs/layering-real-stack-results-round3.md`.",
        "",
        f"Protocol: {runs} runs per case.",
        "",
        "## Environment",
        "",
        "```text",
        environment.rstrip(),
        "```",
        "",
        "## Verdicts",
        "",
        "| Prediction | Case | Verdict | Detail |",
        "|---|---|---|---|",
    ]
    for item in verdicts:
        lines.append(
            f"| {item['prediction']} | {item['case']} | **{item['verdict']}** | {item['detail']} |"
        )
    lines += [
        "",
        f"Brier score: **{brier:.4f}** over {scored} scored predictions.",
        "",
        "Missing from the run: " + (", ".join(missing) if missing else "nothing") + ".",
        "",
        "Unscored (INCONCLUSIVE, INVALID or NOT RUN): "
        + (", ".join(unscored) if unscored else "nothing")
        + ".",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def write_calibration(path: Path, rows: list[dict[str, object]]) -> None:
    lines = ["| Prediction | Credence | Outcome | Brier |", "|---|---:|---:|---:|"]
    for row in rows:
        lines.append(
            f"| {row['key']} | {row['credence']:.2f} | {row['outcome']} | {row['brier']:.4f} |"
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _recompute(out: Path) -> int:
    path = out / "observations.csv"
    if not path.exists():
        raise SystemExit(f"no observations at {path}")
    rows: list[dict[str, object]] = []
    with path.open(newline="", encoding="utf-8") as handle:
        for record in csv.DictReader(handle):
            rows.append(
                {
                    "source": record["source"],
                    "scenario": record["scenario"],
                    "policy": record["policy"],
                    "seed": int(record["seed"]),
                    "metric": record["metric"],
                    "value": float(record["value"]),
                    "unit": record["unit"],
                }
            )
    environment = (
        (out / "environment.txt").read_text(encoding="utf-8")
        if (out / "environment.txt").exists()
        else ""
    )
    verdicts = all_verdicts(rows)
    brier, scored, missing, unscored = brier_score(verdicts)
    write_verdicts(out / "verdicts.csv", verdicts)
    write_calibration(out / "calibration.md", calibration_table(verdicts))
    write_summary(out / "summary.md", environment, verdicts, 20, brier, scored, missing, unscored)
    for item in verdicts:
        print(f"{item['case']:8s} {item['verdict']:13s} {item['detail']}")
    print(f"Brier: {brier:.4f} over {scored} scored predictions")
    return 0


def _not_run_reason(case_id: str, facilities: dict[str, str | None]) -> str | None:
    required = ["netns", "veth", "xfrm_esp", "replay_window", "tool:tc"]
    if case_id == "P17a":
        required.append("tc_netem_reorder")
    for name in required:
        if facilities.get(name):
            return f"{name}: {facilities[name]}"
    if facilities.get("root"):
        return str(facilities["root"])
    if facilities.get("af_packet"):
        return str(facilities["af_packet"])
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", default="", help="comma list of case ids, e.g. P17a,P17b")
    parser.add_argument("--runs", type=int, default=20)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--probe", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--recompute", action="store_true")
    args = parser.parse_args(argv)

    if args.recompute:
        return _recompute(args.output_dir)

    cases = select_cases(args.only)
    shell = Shell()
    facilities = probe(shell)
    facilities["root"] = None if (hasattr(os, "geteuid") and os.geteuid() == 0) else "not root"
    try:
        import socket

        socket.socket(socket.AF_PACKET, socket.SOCK_RAW, socket.htons(3)).close()
        facilities["af_packet"] = None
    except Exception as error:  # noqa: BLE001
        facilities["af_packet"] = f"AF_PACKET unavailable: {error}"

    if args.probe:
        for name, reason in facilities.items():
            print(f"{name:18s} {'ok' if reason is None else 'MISSING: ' + str(reason)}")
        for case in cases:
            reason = _not_run_reason(case.id, facilities)
            print(f"{case.id:8s} {'can run' if reason is None else 'NOT RUN: ' + reason}")
        return 0

    if args.dry_run:
        for case in cases:
            run_case(case, 0, Shell(dry_run=True))
        return 0

    out = args.output_dir
    out.mkdir(parents=True, exist_ok=True)
    environment = environment_record(shell)
    (out / "environment.txt").write_text(environment, encoding="utf-8")

    cleanup_leftovers(shell)
    rows: list[dict[str, object]] = []
    errors: list[str] = []
    not_run: list[dict[str, str]] = []
    for case in cases:
        reason = _not_run_reason(case.id, facilities)
        if reason:
            not_run.append(
                {"prediction": case.id, "case": case.id, "verdict": NOT_RUN, "detail": reason}
            )
            print(f"{case.id}: NOT RUN ({reason})", file=sys.stderr)
            continue
        for run in range(args.runs):
            print(f"{case.id}: run {run + 1}/{args.runs}", file=sys.stderr, flush=True)
            try:
                rows.extend(run_case(case, run, shell))
            except (CommandError, RuntimeError, OSError) as error:
                errors.append(f"{case.id} run {run}: {error}")
                rows.append(
                    {
                        "source": "linux_real_stack_round3",
                        "scenario": case.id,
                        "policy": case.id,
                        "seed": run,
                        "metric": "setup_error",
                        "value": 1,
                        "unit": "boolean",
                    }
                )
                cleanup_leftovers(shell)
                for name in ("rs2A", "rs2A2", "rs2N", "rs2B"):
                    shell.run(["ip", "netns", "del", name], check=False)
                for veth in ("vA1", "vN1", "vA3", "vN3", "vN2", "vB2"):
                    shell.run(["ip", "link", "del", veth], check=False)

    if rows:
        write_observations(out / "observations.csv", rows)
    selected_ids = [case.id for case in cases if case.id != "P17f"]
    if any(case in selected_ids for case in ("P17b", "P17c", "P17d", "P17e")):
        selected_ids.append("P17f")
    verdicts = all_verdicts(rows, selected_ids) + not_run
    brier, scored, missing, unscored = brier_score(verdicts)
    (out / "errors.txt").write_text("\n".join(errors) + ("\n" if errors else ""), encoding="utf-8")
    write_verdicts(out / "verdicts.csv", verdicts)
    write_calibration(out / "calibration.md", calibration_table(verdicts))
    write_summary(out / "summary.md", environment, verdicts, args.runs, brier, scored, missing, unscored)
    for item in verdicts:
        print(f"{item['case']:8s} {item['verdict']:13s} {item['detail']}")
    print(f"Brier: {brier:.4f} over {scored} scored predictions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
