"""Run the real-stack predictions P8-P12.

Examples (Linux, as root; see ``validation/real_stack/README.md``)::

    python3 -m validation.real_stack.run --probe
    python3 -m validation.real_stack.run --dry-run --only P8a      # print the commands only
    python3 -m validation.real_stack.run --only P9 --runs 2        # smoke test
    python3 -m validation.real_stack.run                           # the frozen protocol: 20 runs per case

Outputs go to ``validation/real_stack/results``: ``observations.csv`` (layering
schema), ``verdicts.csv``, ``environment.txt``, ``errors.txt`` and ``summary.md``.
The hand-maintained ``docs/layering-real-stack-results.md`` is never touched.
"""

from __future__ import annotations

import argparse
import csv
import platform
import shutil
import sys
from datetime import datetime, timezone
from pathlib import Path

from validation.layering._io import write_observations

from .cases import Case, RunConfig, run_case, select_cases
from .probe import not_run_reason, probe, requirements
from .shell import REPO_ROOT, CommandError, Shell
from .topology import cleanup_leftovers
from .verdict import NOT_RUN, all_verdicts

DEFAULT_OUTPUT = REPO_ROOT / "validation" / "real_stack" / "results"


def environment_record(shell: Shell) -> str:
    def first_line(argv: list[str]) -> str:
        if shutil.which(argv[0]) is None:
            return "not installed"
        result = shell.run(argv, check=False)
        text = (result.stdout or result.stderr).strip().splitlines()
        return text[0] if text else "unknown"

    try:
        proc_version = Path("/proc/version").read_text(encoding="utf-8").strip()
    except OSError:
        proc_version = "unavailable"
    lines = [
        f"date_utc: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        f"python: {platform.python_version()}",
        f"kernel: {platform.release()}",
        f"proc_version: {proc_version}",
        f"wsl2: {'microsoft' in proc_version.lower()}",
        f"ip: {first_line(['ip', '-V'])}",
        f"wg: {first_line(['wg', '--version'])}",
        f"nft: {first_line(['nft', '--version'])}",
        f"tc: {first_line(['tc', '-V'])}",
        f"ethtool: {first_line(['ethtool', '--version'])}",
    ]
    return "\n".join(lines) + "\n"


def write_verdicts(path: Path, verdicts: list[dict[str, str]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=("prediction", "case", "verdict", "detail"))
        writer.writeheader()
        writer.writerows(verdicts)


def write_summary(path: Path, environment: str, verdicts: list[dict[str, str]], config: RunConfig) -> None:
    lines = [
        "# Real-stack run summary (generated)",
        "",
        "Generated by `python -m validation.real_stack.run`; **do not edit by hand**.",
        "Interpretation belongs in `docs/layering-real-stack-results.md`.",
        "",
        f"Protocol: {config.runs} runs per case, {config.datagrams} datagrams per delivery run, "
        f"{config.packets_per_length} packets per length in size sweeps.",
        "",
        "## Environment",
        "",
        "```text",
        environment.rstrip(),
        "```",
        "",
        "## Verdicts",
        "",
        "| Prediction | Case | Verdict | Detail |",
        "|---|---|---|---|",
    ]
    for item in verdicts:
        lines.append(f"| {item['prediction']} | {item['case']} | **{item['verdict']}** | {item['detail']} |")
    lines += [
        "",
        "Dispositions: CONFIRMED, REFUTED, INCONCLUSIVE (cause gate failed), INVALID (mutation gate or",
        "control failed, or setup error), NOT RUN (facility missing). Neither INVALID nor NOT RUN",
        "is evidence for or against a prediction.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def _dry_run(cases: list[Case], config: RunConfig) -> int:
    for case in cases:
        shell = Shell(dry_run=True)
        run_case(case, 0, config, shell)
        print(f"# --- {case.id}: {case.label}  (needs: {', '.join(requirements(case))})")
        print(shell.script())
        print()
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", default="", help="comma list of case ids or prediction ids, e.g. P8,P11a")
    parser.add_argument("--runs", type=int, default=20)
    parser.add_argument("--datagrams", type=int, default=50)
    parser.add_argument("--packets-per-length", type=int, default=5)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--probe", action="store_true", help="report available kernel facilities and exit")
    parser.add_argument("--dry-run", action="store_true", help="print the commands of one run per case and exit")
    args = parser.parse_args(argv)

    config = RunConfig(runs=args.runs, datagrams=args.datagrams, packets_per_length=args.packets_per_length)
    cases = select_cases(args.only)

    if args.dry_run:
        return _dry_run(cases, config)

    shell = Shell()
    facilities = probe(shell)
    if args.probe:
        for name, reason in facilities.items():
            print(f"{name:16s} {'ok' if reason is None else 'MISSING: ' + reason}")
        for case in cases:
            reason = not_run_reason(case, facilities)
            print(f"{case.id:12s} {'can run' if reason is None else 'NOT RUN: ' + reason}")
        return 0

    out = args.output_dir
    out.mkdir(parents=True, exist_ok=True)
    environment = environment_record(shell)
    (out / "environment.txt").write_text(environment, encoding="utf-8")

    cleanup_leftovers(shell)
    rows: list[dict[str, object]] = []
    errors: list[str] = []
    not_run: list[dict[str, str]] = []
    for case in cases:
        reason = not_run_reason(case, facilities)
        if reason:
            not_run.append({"prediction": case.prediction, "case": case.id, "verdict": NOT_RUN, "detail": reason})
            print(f"{case.id}: NOT RUN ({reason})", file=sys.stderr)
            continue
        for run in range(args.runs):
            print(f"{case.id}: run {run + 1}/{args.runs}", file=sys.stderr)
            try:
                rows.extend(run_case(case, run, config, shell))
            except (CommandError, RuntimeError, OSError) as error:
                errors.append(f"{case.id} run {run}: {error}")
                rows.append({"source": "linux_real_stack", "scenario": case.prediction, "policy": case.id, "seed": run,
                             "metric": "setup_error", "value": 1, "unit": "boolean"})
                cleanup_leftovers(shell)

    if rows:
        write_observations(out / "observations.csv", rows)
    verdicts = all_verdicts(rows) + not_run
    (out / "errors.txt").write_text("\n".join(errors) + ("\n" if errors else ""), encoding="utf-8")
    write_verdicts(out / "verdicts.csv", verdicts)
    write_summary(out / "summary.md", environment, verdicts, config)
    for item in verdicts:
        print(f"{item['case']:14s} {item['verdict']:13s} {item['detail']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
